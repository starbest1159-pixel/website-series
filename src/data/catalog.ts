function buildEpisodes(
  count: number,
  minutes: number,
  thumbnail: string,
  titles: string[]
): Episode[] {
  const durationSeconds = minutes * 60;
  const durationLabel = `${String(minutes).padStart(2, '0')}:00`;
  return Array.from({ length: count }, (_, idx) => {
    const epNum = idx + 1;
    const customTitle = titles[idx % titles.length];
    return {
      number: epNum,
      title: `ตอนที่ ${epNum}: ${customTitle}`,
      durationSeconds,
      durationLabel,
      summary: `ติดตามเรื่องราวเข้มข้นในตอนที่ ${epNum} พร้อมภาพคมชัดระดับ HD และซับไทยสมบูรณ์แบบ`,
      thumbnail,
    };
  });
}

